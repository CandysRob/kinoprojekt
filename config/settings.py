load_dotenv(BASE_DIR / ".env")


def env(name, default=None):
    value = os.environ.get(name, default)
    if value is None:
        raise ImproperlyConfigured(f"Keskkonnamuutuja {name} puudub (vaata .env.example).")
    return value


